"""
R_FC Group from event-summary CSV files.

Input
-----
One or more dfc_features_summary.csv files generated by the DFC synthesis
pipeline. Required feature columns are:
    - N_DFC_event
    - DFC_event_mean_h

Output
------
dfc_features_with_clusters.csv
    Original event-summary rows plus:
    - monthly_cluster
    - monthly_cluster_name

Cluster definition
------------------
K-means clustering is performed using N_DFC_event and DFC_event_mean_h after
excluding rows with N_DFC_event <= 0 from model fitting. Rows with N_DFC_event <= 0
remain in the output with missing cluster labels.

Cluster IDs are semantically relabeled as:
    0: Minimal R_FC
    1: Frequent R_FC
    2: Long R_FC

The semantic relabeling rule is deterministic:
    - Long R_FC: cluster with the largest centroid DFC_event_mean_h
    - Frequent R_FC: among the remaining clusters, the cluster with the larger
      centroid N_DFC_event
    - Minimal R_FC: the remaining cluster
"""

